                    <h2 class="gap-top">FAQ</h2>
                    <h4>What industries benefit from AI voicebots? </h4>
                    <p class="style">Retail, banking, healthcare, telecom, and logistics use AI voicebots for support,
                        scheduling, marketing, order updates, and many other purposes.</p>

                    <h4>Are AI voicebots safe? </h4>
                    <p>Most systems follow strong security protocols. However, always confirm it with your provider.</p>

                    <h4>How long does the setup take? </h4>
                    <p>A simple bot can be ready in days. A custom AI voicebot may take weeks, depending on the required
                        features.</p>

                    <h4>Are AI voicebots expensive? </h4>
                    <p>The initial setup cost can be high. But over time, it saves money compared to hiring new agents.
                    </p>

