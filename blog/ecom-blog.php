                    <p class="style">
                        AI voicebots can proactively initiate outbound calls to customers who abandoned their cart
                        without checking out. The bot can inform the customer about their left-out cart, answer relevant
                        questions, give assistance to complete the order, and even offer a special deal to complete the
                        sale.
                    </p>

                    <h4>How It Works</h4>
                    <p>Below is the simple workflow of this process:</p>
                    <ul>
                        <li>When someone abandons a cart, the AI detects it from the system and makes a call within the
                            hour.</li>
                        <li>It asks the customer whether she’s still interested in the product and offers help to
                            complete the order.</li>
                        <li>If relevant, it can offer the customer a time-limited discount.</li>
                    </ul>

