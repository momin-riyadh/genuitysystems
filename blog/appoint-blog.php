                    <h4>How AI Reminder Calls Work</h4>
                    <p class="style">
                        Here’s how AI reminder calls work in simple terms:
                    </p>

                    <h4>Linking to Your Calendar & CRM</h4>
                    <p class="style">
                        The AI system will connect with your scheduling tool, such as Google Calendar, CRM, or any
                        custom app you use.
                    </p>

                    <h4>Automatic Triggering</h4>
                    <p class="style">
                        You choose when you want the reminder—like 24 or 48 hours before the appointment. The system
                        automatically kicks off the call.
                    </p>

                    <h4>Natural Language Interaction</h4>
                    <p class="style">
                        The AI starts the call with “Hi, Mr X, this is XYZ hospital. You’ve got an appointment coming
                        up.” The client just talks back like they would with a human agent.
                    </p>

                    <h4>Action Handling</h4>
                    <p class="style">
                        The client speaks with the AI agent. She will either keep the appointment, change or cancel it.
                        AI system listens to the client carefully and updates the record.
                    </p>

                    <h4>Real Time Notification</h4>
                    <p class="style">
                        If the client changes or cancels the appointment, the system will send a notification as an
                        instant update of the changes.
                    </p>

