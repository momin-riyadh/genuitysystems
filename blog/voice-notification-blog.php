                    <h2 class="gap-top">FAQ</h2>

                    <h4>What exactly is a transactional voice notification?</h4>
                    <p class="style">
                        A transactional voice notification is an automated phone call that happens when a customer takes
                        a certain action. For example, when they buy something, make a payment, or ask for a one-time
                        passcode (OTP), a transactional notification is generated from the system. These calls give the
                        customers important information on purchases, delivery and other updates.
                    </p>

                    <h4>How does AI make voice notifications better?</h4>
                    <p class="style">
                        AI makes voice notifications smarter and more helpful. It lets the system create messages on the
                        spot. It sounds more like a real person. The messages are not static; rather, the system can
                        create personalized messages for each customer. It ensures a better user experience.
                    </p>

                    <h4>Are AI voice notifications better than SMS or email?</h4>
                    <p class="style">
                        Yes, for most cases. Voice calls arrive faster, draw more attention, and work for people who
                        might overlook a text or email. Transactional voice messages can be urgent, such as fraud alerts
                        or delivery updates.
                    </p>

                    <h4>Can AI voice notifications be personalized for each customer?</h4>
                    <p class="style">
                        Definitely. AI can use customer details from the CRM, such as name, order number, preferred
                        language, and locatio,n to make each call personalized.
                    </p>

                    <h4>Which industries can benefit from transactional AI voice notifications?</h4>
                    <p class="style">
                        Industries like e-commerce, banking, telecommunication, logistics, healthcare, and tourism may
                        use AI voice notifications to keep people updated about their transactions and other important
                        information.
                    </p>

                    <h4>Are these voice calls actually interactive?</h4>
                    <p class="style">
                        Not all AI voice notifications are interactive. AI voice alerts can be interactive if required.
                        It means you can tap a button or say something to give the system an instruction and carry on
                        the conversation.
                    </p>


